test('reset preserves interrupted source and a failed rerun cannot submit an earlier forecast', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Open final challenge', exact: true }).click();
  const challenge = page.getByRole('region', { name: 'Final challenge', exact: true });
  const editor = challenge.getByLabel('Final Python', { exact: true });
  const run = challenge.getByRole('button', { name: 'Run final forecast', exact: true });
  const submit = challenge.getByRole('button', { name: 'Commit stock and submit challenge', exact: true });
  await challenge.getByLabel('Final expectation').fill('An interrupted run must keep its source.');
  await editor.fill('while True:\n    pass');
  await expect(run).toBeEnabled({ timeout: 90_000 });
  await run.click();
  await expect(challenge.getByRole('button', { name: 'Stop final run' })).toBeVisible();
  await challenge.getByRole('button', { name: 'Reset final Python' }).click();
  await challenge.getByText('Final experiment history (1 runs)', { exact: true }).click();
  await challenge.getByText('Run 1: failed', { exact: true }).click();
  await expect(challenge).toContainText('An interrupted run must keep its source.');
  await expect(challenge).toContainText('Run interrupted by reset.');
  await expect(challenge.locator('pre').filter({ hasText: 'while True:' })).toBeVisible();
  await expect(submit).toBeDisabled();
  await editor.fill(solution);
  await expect(run).toBeEnabled({ timeout: 90_000 });
  await run.click();
  await expect(submit).toBeEnabled();
  await editor.fill('raise ValueError("final rerun failed")');
  await run.click();
  await expect(challenge.getByRole('alert')).toContainText('final rerun failed');
  await expect(submit).toBeDisabled();
  await expect(challenge.getByRole('table', { name: 'Final evaluation answers' })).toHaveCount(0);
});
